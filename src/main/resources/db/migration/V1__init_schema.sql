-- ==========================================
-- ENUMS & TYPES
-- ==========================================

CREATE TYPE appointment_status_type AS ENUM (
    'Scheduled',
    'Scheduled (confirmed)',
    'Cancelled',
    'In-Consultation',
    'Completed',
    'Missed'
);

CREATE TYPE gender_type AS ENUM (
	'Male',
	'Female',
	'Not prefer'
);


-- Table: addresses
CREATE TABLE addresses (
                           id int GENERATED BY DEFAULT AS IDENTITY,
                           street_name varchar(255)  NOT NULL,
                           city_name varchar(255)  NOT NULL,
                           house_number varchar(255)  NOT NULL,
                           state_name varchar(255)  NOT NULL,
                           apartment_number varchar(255)  NOT NULL,
                           zip_code varchar(255)  NOT NULL,
                           phone varchar(255),
                           CONSTRAINT addresses_pk PRIMARY KEY (id)
);

-- Table: appointments
CREATE TABLE appointments (
                              id int GENERATED BY DEFAULT AS IDENTITY,
                              scheduled_date date  NOT NULL,
                              status appointment_status_type  NOT NULL,
                              doctor_id int  NOT NULL,
                              patient_id int  NOT NULL,
                              service_id int  NOT NULL,
                              created_at timestamp  NOT NULL DEFAULT CURRENT_TIMESTAMP,
                              updated_at timestamp  NOT NULL DEFAULT CURRENT_TIMESTAMP,
                              CONSTRAINT appointments_pk PRIMARY KEY (id),
                              CONSTRAINT chk_updated_after_created CHECK (updated_at >= created_at)
);

-- Table: clinics
CREATE TABLE clinics (
                         id int GENERATED BY DEFAULT AS IDENTITY,
                         name varchar(255)  NOT NULL,
                         logo_url varchar(255),
                         description text,
                         address_id int  NOT NULL,
                         CONSTRAINT clinics_pk PRIMARY KEY (id)
);

-- Table: doctor_availabilities
CREATE TABLE doctor_availabilities (
                                       id int GENERATED BY DEFAULT AS IDENTITY,
                                       start_time time  NOT NULL,
                                       end_time time  NOT NULL,
                                       time_step_minutes int  NOT NULL,
                                       availability_date date  NOT NULL,
                                       doctor_id int  NOT NULL,
                                       CONSTRAINT doctor_availabilities_pk PRIMARY KEY (id),
                                       CONSTRAINT chk_end_after_start CHECK (end_time > start_time),
                                       CONSTRAINT chk_step_positive CHECK (time_step_minutes > 0)
);

-- Table: doctor_specializations
CREATE TABLE doctor_specializations (
                                        doctor_id int  NOT NULL,        -- Fixed naming (was doctors_id)
                                        specialization_id int  NOT NULL,
                                        CONSTRAINT doctor_specializations_pk PRIMARY KEY (doctor_id, specialization_id)
);

-- Table: doctors
CREATE TABLE doctors (
                         id int GENERATED BY DEFAULT AS IDENTITY,
                         bio varchar(255)  NOT NULL,
                         user_id int  NOT NULL,
                         clinic_id int  NOT NULL,
                         CONSTRAINT doctors_pk PRIMARY KEY (id)
);

-- Table: online_consultation
CREATE TABLE online_consultation (
                                     appointment_id int  NOT NULL,
                                     meeting_link varchar(255),
                                     CONSTRAINT online_consultation_pk PRIMARY KEY (appointment_id)
);

-- Table: patients
CREATE TABLE patients (
                          id int GENERATED BY DEFAULT AS IDENTITY,
                          citizenship varchar(255)  NOT NULL,
                          gender gender_type  NOT NULL,
                          date_of_birth date  NOT NULL,
                          user_id int  NOT NULL,
                          address_id int  NOT NULL,
                          CONSTRAINT patients_pk PRIMARY KEY (id),
                          CONSTRAINT chk_dob_valid CHECK (date_of_birth > '1915-01-01')
);

-- Table: roles
CREATE TABLE roles (
                       id int GENERATED BY DEFAULT AS IDENTITY,
                       name varchar(50)  NOT NULL,
                       CONSTRAINT roles_pk PRIMARY KEY (id)
);

-- Table: service_categories
CREATE TABLE service_categories (
                                    id int GENERATED BY DEFAULT AS IDENTITY,
                                    name varchar(255)  NOT NULL,
                                    specialization_id int  NOT NULL,
                                    CONSTRAINT service_categories_pk PRIMARY KEY (id)
);

-- Table: services
CREATE TABLE services (
                          id int GENERATED BY DEFAULT AS IDENTITY,
                          name varchar(255)  NOT NULL,
                          description text,
                          price decimal(10,2)  NOT NULL,
                          duration_minutes int  NOT NULL,
                          service_category_id int  NOT NULL,
                          CONSTRAINT services_pk PRIMARY KEY (id),
                          CONSTRAINT chk_price_positive CHECK (price >= 0),
                          CONSTRAINT chk_duration_positive CHECK (duration_minutes > 0)
);

-- Table: specializations
CREATE TABLE specializations (
                                 id int GENERATED BY DEFAULT AS IDENTITY,
                                 name varchar(50)  NOT NULL,
                                 description varchar(255)  NOT NULL,
                                 CONSTRAINT specializations_pk PRIMARY KEY (id)
);

-- Table: tests
CREATE TABLE tests (
                       appointment_id int  NOT NULL,
                       result_url varchar(255),
                       uploaded_at timestamp,
                       CONSTRAINT tests_pk PRIMARY KEY (appointment_id)
);

-- Table: user_roles
CREATE TABLE user_roles (
                            user_id int  NOT NULL,
                            role_id int  NOT NULL,
                            CONSTRAINT user_roles_pk PRIMARY KEY (user_id, role_id)
);

-- Table: users
CREATE TABLE users (
                       id int GENERATED BY DEFAULT AS IDENTITY,
                       email varchar(255)  NOT NULL,
                       password_hash varchar(255)  NOT NULL,
                       first_name varchar(255)  NOT NULL,
                       last_name varchar(255)  NOT NULL,
                       profile_url varchar(255),
                       CONSTRAINT unique_email UNIQUE (email),
                       CONSTRAINT users_pk PRIMARY KEY (id)
);

-- Table: visits
CREATE TABLE visits (
                        appointment_id int  NOT NULL,
                        diagnosis text,
                        symptoms text,
                        cabinet_number varchar(20)  NOT NULL,
                        medical_report text,
                        CONSTRAINT visits_pk PRIMARY KEY (appointment_id)
);